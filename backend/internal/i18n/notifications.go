package i18n

// Messages of e-mail notifications, filter subscriptions and webhooks
// (packages notify and api), kept in their own file and merged into the
// catalogues at start. An entry the main catalogue already has wins.
func init() {
	for locale, msgs := range map[string]map[string]string{"en": notifyEN, "de": notifyDE, "it": notifyIT, "hi": notifyHI} {
		for k, v := range msgs {
			if _, ok := catalogues[locale][k]; !ok {
				catalogues[locale][k] = v
			}
		}
	}
}

