package tests

// What each change to an account's credentials ends: its sessions, its
// personal access tokens and the links mailed to it. A new password, a
// deactivation and a reactivation end all three, except the session that
// changes its own password; an address change only ends the links.

import (
	"bytes"
	"context"
	"errors"
	"net/url"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
	"time"

	"solstice/internal/audit"
	"solstice/internal/auth"
	"solstice/internal/config"
)

const credentialPassword = "first credential passphrase"

// credentials are what can sign an account in, besides its password.
type credentials struct {
	current string // the session of the person's own browser
	other   string // a session on another device
	token   string // a personal access token
	link    string // a reset link
}

// survivors tells which credentials still work.
type survivors struct{ Current, Other, Token, Link bool }

func plantCredentials(t *testing.T, me *client, id int64, username string) credentials {
	t.Helper()
	ctx := context.Background()
	c := credentials{token: newToken(t, username, nil)}
	u, _ := url.Parse(me.base)
	for _, k := range me.http.Jar.Cookies(u) {
		if k.Name == auth.CookieName {
			c.current = k.Value
		}
	}
	if c.current == "" {
		t.Fatal("no session cookie")
	}
	var err error
	if c.other, _, err = auth.NewSession(ctx, testDB, id); err != nil {
		t.Fatal(err)
	}
	tx, err := testDB.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer tx.Rollback()
	if c.link, err = auth.IssueAccountToken(ctx, tx, id, auth.PurposeReset, time.Now()); err != nil {
		t.Fatal(err)
	}
	if err := tx.Commit(); err != nil {
		t.Fatal(err)
	}
	return c
}

func (c credentials) survivors(t *testing.T) survivors {
	t.Helper()
	ctx := context.Background()
	works := func(err error) bool {
		if err != nil && !errors.Is(err, auth.ErrNoSession) && !errors.Is(err, auth.ErrBadToken) {
			t.Fatal(err)
		}
		return err == nil
	}
	_, current := auth.Lookup(ctx, testDB, c.current)
	_, other := auth.Lookup(ctx, testDB, c.other)
	_, token := auth.LookupToken(ctx, testDB, c.token)
	_, link := auth.LookupAccountToken(ctx, testDB, c.link, time.Now())
	return survivors{works(current), works(other), works(token), works(link)}
}

// passwdCommand runs `solstice user passwd` on the test database.
func passwdCommand(t *testing.T, username, password string) {
	t.Helper()
	bin := filepath.Join(t.TempDir(), "solstice")
	if out, err := exec.Command("go", "build", "-o", bin, "solstice/cmd/solstice").CombinedOutput(); err != nil {
		t.Fatalf("go build: %v\n%s", err, out)
	}
	cmd := exec.Command(bin, "user", "passwd", "-username", username, "-password", password)
	cmd.Env = append(os.Environ(), config.KeyDBURL+"="+os.Getenv("SOLSTICE_TEST_DB"),
		config.KeyConfig+"="+filepath.Join(t.TempDir(), "absent.conf"))
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		t.Fatalf("solstice user passwd: %v: %s", err, stderr.String())
	}
}

func TestWhatSurvivesACredentialChange(t *testing.T) {
	admin := login(t, "admin", "admin")
	for _, c := range []struct {
		event  string
		change func(t *testing.T, me *client, path, username string, creds credentials)
		want   survivors
		// audited is the entry that counts the deleted access tokens.
		audited string
	}{
		{"own password change", func(t *testing.T, me *client, _, _ string, _ credentials) {
			me.call("PATCH", "/api/me", map[string]any{"currentPassword": credentialPassword,
				"newPassword": "second credential passphrase"}, 200, nil)
		}, survivors{Current: true}, audit.PasswordChange},
		{"own address change", func(t *testing.T, me *client, _, username string, _ credentials) {
			me.call("PATCH", "/api/me", map[string]any{"currentPassword": credentialPassword,
				"email": "moved." + username + "@exemple.fr"}, 200, nil)
		}, survivors{Current: true, Other: true, Token: true}, ""},
		{"password set by an administrator", func(t *testing.T, _ *client, path, _ string, _ credentials) {
			admin.call("PATCH", path, map[string]any{"password": "set by an administrator"}, 204, nil)
		}, survivors{}, audit.PasswordChange},
		{"address changed by an administrator", func(t *testing.T, _ *client, path, username string, _ credentials) {
			admin.call("PATCH", path, map[string]any{"email": "moved." + username + "@exemple.fr"}, 204, nil)
		}, survivors{Current: true, Other: true, Token: true}, ""},
		{"password generated by an administrator", func(t *testing.T, _ *client, path, _ string, _ credentials) {
			admin.call("POST", path+"/reset-password", nil, 200, nil)
		}, survivors{}, audit.PasswordReset},
		{"reset link used", func(t *testing.T, _ *client, _, _ string, creds credentials) {
			anonymous(t).call("POST", "/api/auth/reset", map[string]string{"token": creds.link,
				"password": "chosen through the link"}, 200, nil)
		}, survivors{}, audit.PasswordResetDone},
		{"solstice user passwd", func(t *testing.T, _ *client, _, username string, _ credentials) {
			passwdCommand(t, username, "set on the command line")
		}, survivors{}, audit.PasswordChange},
		{"deactivation, then reactivation", func(t *testing.T, _ *client, path, _ string, _ credentials) {
			admin.call("PATCH", path, map[string]any{"active": false}, 204, nil)
			admin.call("PATCH", path, map[string]any{"active": true}, 204, nil)
		}, survivors{}, audit.UserDeactivate},
		// An import leaves the sessions and tokens of the accounts it deactivates.
		{"reactivation of an account deactivated elsewhere", func(t *testing.T, _ *client, path, username string, _ credentials) {
			if _, err := testDB.Exec(`UPDATE users SET active = FALSE WHERE username = ?`, username); err != nil {
				t.Fatal(err)
			}
			admin.call("PATCH", path, map[string]any{"active": true}, 204, nil)
		}, survivors{}, audit.UserActivate},
	} {
		t.Run(c.event, func(t *testing.T) {
			id, username := newAccount(t, admin, credentialPassword)
			me := login(t, username, credentialPassword)
			creds := plantCredentials(t, me, id, username)
			if got := creds.survivors(t); got != (survivors{true, true, true, true}) {
				t.Fatalf("before the change: %+v", got)
			}
			c.change(t, me, "/api/admin/users/"+jsonInt(id), username, creds)
			if got := creds.survivors(t); got != c.want {
				t.Errorf("survive: %+v, want %+v", got, c.want)
			}
			if c.audited != "" {
				details := pick(t, `SELECT COALESCE(details, '{}') FROM audit_log
					WHERE action = ? AND target_label = ? ORDER BY id DESC LIMIT 1`, c.audited, username)
				if n := num(obj(t, []byte(details)), "revokedAccessTokens"); n != 1 {
					t.Errorf("%s: %d access tokens revoked in %s, want 1", c.audited, n, details)
				}
			}
		})
	}
}
